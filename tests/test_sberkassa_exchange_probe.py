    def test_manual_scheduled_and_push_runs_use_shared_browser_tabs(self):
        root = Path(__file__).resolve().parents[1]
        caller = (root / ".github" / "workflows" / "sberkassa-exchange-inspection.yml").read_text(encoding="utf-8")
        shared = (root / "scripts" / "keep_browser_and_tunnel_alive.sh").read_text(encoding="utf-8")
        self.assertIn("default: auth_only", caller)
        self.assertIn("- auth_only", caller)
        self.assertIn("THREE_TAB_AUTH_ONLY=YES", shared)
        self.assertIn("ALL_THREE_TABS_AUTHENTICATED", shared)
        self.assertIn("shared_browser_auth_probe.py", shared)
        self.assertIn("SHARED_AUTH_DIAGNOSTICS_UPDATE:", shared)
        self.assertIn("tail -n 8 /tmp/shared-browser-auth.log", shared)
        self.assertIn("- all", caller)
        self.assertIn("github.event_name == 'workflow_dispatch' && inputs.target", caller)
        self.assertIn("github.event_name == 'schedule' && 'all'", caller)
        self.assertIn("github.event_name == 'push' && 'browser_tabs_only'", caller)
        self.assertIn("cron: '*/15 * * * *'", caller)
        self.assertIn("browser_tabs_only", caller)
        self.assertIn('TARGET" = "browser_tabs_only"', shared)
        self.assertIn("BROWSER_TABS_ONLY_READY=YES", shared)
        self.assertIn("BROWSER_TABS_ONLY_WAITING_FOR_MANUAL_VISUAL_CONFIRMATION", shared)
        self.assertIn("CHROMIUM_PROFILE_RESTORED", shared)
        self.assertIn("OPENING_PROTECTED_ROUTES=YES", shared)
        self.assertNotIn("--restore-last-session", shared)
        persistence_workflow = (root / ".github" / "workflows" / "browserless-eid-handoff-stable.yml").read_text(encoding="utf-8")
        self.assertIn("verify-restored-three-tab-session", persistence_workflow)
        self.assertIn("CHROMIUM_AUTH_PROFILE_SAVE=STARTED", persistence_workflow)
        self.assertNotIn("CHROMIUM_SESSION_RESTORE_DATA_MISSING", persistence_workflow)
        self.assertIn("RESTORED_THREE_TAB_SESSION=VERIFIED", persistence_workflow)
        self.assertNotIn("--restore-last-session", persistence_workflow)
        self.assertIn("https://storage.money/deals#tab-3", persistence_workflow)
        self.assertIn("https://sberkassa.site/deals#tab-3", persistence_workflow)
        self.assertIn("https://sberkassa.site/exchange", persistence_workflow)
        self.assertIn('STATUS=""', shared)
        self.assertIn(': > /tmp/eid-browser.log', shared)
        self.assertLess(shared.index(': > /tmp/eid-browser.log'), shared.index('for i in $(seq 1 900); do'))
        self.assertIn("SHARED_CHROMIUM_THREE_TARGET_TABS=VERIFIED", shared)
        self.assertIn("SHARED_CHROMIUM_DISTINCT_TARGET_IDS=3", shared)
        self.assertIn("CHROMIUM_SINGLE_PROCESS=YES PID=$BROWSER_PID", shared)
        self.assertIn("CHROMIUM_SHARED_PROFILE=YES", shared)
        self.assertIn("ALL_THREE_SHARED_BROWSER_TABS_COMPLETE=YES", shared)
        money = (root / "scripts" / "money_storage_chromium_bridge.py").read_text(encoding="utf-8")
        deals = (root / "scripts" / "sberkassa_chromium_probe.py").read_text(encoding="utf-8")
        exchange = (root / "scripts" / "sberkassa_exchange_chromium_probe.py").read_text(encoding="utf-8")
        self.assertIn('urlparse(item.get("url", "")).hostname == "storage.money"', money)
        self.assertIn('urlparse(item.get("url", "")).hostname == "sberkassa.site"', deals)
        self.assertIn('urlparse(x.get("url", "")).path.rstrip("/") == "/exchange"', exchange)
        self.assertNotIn("targets[0]", money)
        self.assertNotIn("targets[0]", deals)
        self.assertNotIn("targets[0]", exchange)


